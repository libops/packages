// Package pipeline generates native Actions graphs and constrained Renovate rules.
package pipeline

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/libops/packages/internal/catalog"
)

func Workflow(root string, c catalog.Catalog) (string, error) {
	template, err := os.ReadFile(filepath.Join(root, "ci/push.yml.template"))
	if err != nil {
		return "", err
	}
	var jobs []string
	all := []string{"plan", "install-check"}
	for _, name := range c.Names() {
		p := c[name]
		profiles, err := c.Platforms(root, name)
		if err != nil {
			return "", err
		}
		platforms, err := json.Marshal(profiles)
		if err != nil {
			return "", err
		}
		needs := []string{"plan"}
		contexts := []string{}
		condition := "always() && !cancelled() && needs.plan.result == 'success' && contains(fromJSON(needs.plan.outputs.targets), '" + name + "')"
		for _, dep := range p.Dependencies {
			needs = append(needs, "build-"+dep)
			contexts = append(contexts, dep+"=${{ needs.build-"+dep+".outputs.context }}")
			condition += " && (needs.build-" + dep + ".result == 'success' || needs.build-" + dep + ".result == 'skipped')"
		}
		jobs = append(jobs, fmt.Sprintf(`  build-%s:
    needs: [%s]
    if: ${{ %s }}
    concurrency:
      group: target-%s-${{ github.event_name == 'pull_request' && github.event.pull_request.number || ((github.event_name == 'schedule' || (github.event_name == 'workflow_dispatch' && inputs.all == true)) && format('validation-{0}', github.run_id)) || 'main' }}
      cancel-in-progress: false
      queue: max
    uses: ./.github/workflows/build.yml
    with:
      package: %s
      validate-only: ${{ github.event_name == 'schedule' || (github.event_name == 'workflow_dispatch' && inputs.all == true) }}
      local-builder: ${{ needs.plan.outputs.local-builder == 'true' }}
      platforms: '%s'
      contexts: '%s'
    secrets:
      REGISTRY_USER: ${{ (github.event_name != 'pull_request' || github.event.pull_request.head.repo.full_name == github.repository) && secrets.REGISTRY_USER || '' }}
      REGISTRY_PASSWORD: ${{ (github.event_name != 'pull_request' || github.event.pull_request.head.repo.full_name == github.repository) && secrets.REGISTRY_PASSWORD || '' }}
    permissions:
      contents: read
      packages: write
  test-%s:
    if: ${{ github.event_name != 'pull_request' || github.event.pull_request.head.repo.full_name == github.repository }}
    needs: [build-%s]
    uses: ./.github/workflows/test.yml
    with:
      package: %s
      platforms: '%s'
      local-builder: ${{ needs.build-%s.outputs.local-builder == 'true' }}
      context: ${{ needs.build-%s.outputs.context }}
      contexts: ${{ needs.build-%s.outputs.contexts }}
    permissions:
      contents: read
      packages: read
    secrets:
      REGISTRY_USER: ${{ (github.event_name != 'pull_request' || github.event.pull_request.head.repo.full_name == github.repository) && secrets.REGISTRY_USER || '' }}
      REGISTRY_PASSWORD: ${{ (github.event_name != 'pull_request' || github.event.pull_request.head.repo.full_name == github.repository) && secrets.REGISTRY_PASSWORD || '' }}
`, name, strings.Join(needs, ", "), condition, name, name, string(platforms), strings.Join(contexts, " "), name, name, name, string(platforms), name, name, name))
		all = append(all, "build-"+name, "test-"+name)
	}
	text := strings.ReplaceAll(string(template), "# @@JOBS@@", strings.Join(jobs, "\n"))
	text = strings.ReplaceAll(text, "'@@NEEDS@@'", strings.Join(all, ", "))
	return "# Generated by make dev-generate.\n" + text, nil
}
func Renovate(c catalog.Catalog) map[string]any {
	var managers, rules []any
	for _, name := range c.Names() {
		p := c[name]
		if p.Family == "openjdk" {
			continue // Source provenance must be settled before discovering updates.
		}
		update := p.Update
		dep := name + "-source"
		field := "pkgver"
		if update.Tag {
			field = "# upstream-tag"
		}
		versioning := update.Versioning
		if versioning == "" {
			versioning = "semver"
		}
		manager := map[string]any{"customType": "regex", "managerFilePatterns": []string{"/^packages/" + regexp.QuoteMeta(p.Target) + "/APKBUILD$/"}, "matchStrings": []string{`(?:^|\n)` + field + `=(?<currentValue>[^\s]+)`}, "datasourceTemplate": update.Datasource, "packageNameTemplate": update.Package, "depNameTemplate": dep, "versioningTemplate": versioning}
		if update.Extract != "" {
			manager["extractVersionTemplate"] = update.Extract
		}
		managers = append(managers, manager)
		rules = append(rules, map[string]any{"matchDepNames": []string{dep}, "allowedVersions": update.Allowed, "minimumReleaseAge": nil, "schedule": []string{}, "postUpgradeTasks": map[string]any{"commands": []string{"make update TARGET=" + name}, "fileFilters": []string{"packages/" + p.Target + "/**"}}})
	}
	for _, base := range c.Bases() {
		parts := strings.Split(base, "/")
		dep := parts[0] + "-" + parts[1] + "-base"
		managers = append(managers, map[string]any{"customType": "regex", "managerFilePatterns": []string{"/^packages/" + regexp.QuoteMeta(base) + `/base-image\.txt$/`}, "matchStrings": []string{parts[0] + `:(?<currentValue>[^@\s]+)@(?<currentDigest>sha256:[a-f0-9]+)`}, "depNameTemplate": dep, "packageNameTemplate": parts[0], "datasourceTemplate": "docker"})
		rules = append(rules, map[string]any{"matchDepNames": []string{dep}, "allowedVersions": "/^" + regexp.QuoteMeta(parts[1]) + `\.[0-9]+$/`, "postUpgradeTasks": map[string]any{"commands": []string{"make revise-base TARGET=" + base}, "fileFilters": []string{"packages/" + base + "/**"}}})
	}
	defaults := []any{
		map[string]any{"matchDepNames": []string{"*-source"}, "ignoreUnstable": true, "automerge": false, "automergeType": "pr", "platformAutomerge": true},
		map[string]any{"matchManagers": []string{"github-actions"}, "postUpgradeTasks": map[string]any{"commands": []string{"make dev-generate"}, "fileFilters": []string{".github/workflows/push.yml"}, "executionMode": "branch"}},
	}
	return map[string]any{"$schema": "https://docs.renovatebot.com/renovate-schema.json", "extends": []string{"config:best-practices", ":rebaseStalePrs"}, "enabledManagers": []string{"custom.regex", "github-actions", "dockerfile", "gomod"}, "ignorePaths": []string{"**/tests/**", ".github/workflows/push.yml"}, "github-actions": map[string]any{"managerFilePatterns": []string{`/^ci/push\.yml\.template$/`}}, "prHourlyLimit": 0, "prConcurrentLimit": 0, "branchConcurrentLimit": 0, "packageRules": append(defaults, rules...), "customManagers": managers}
}
func JSON(value any) ([]byte, error) {
	var output bytes.Buffer
	encoder := json.NewEncoder(&output)
	encoder.SetEscapeHTML(false)
	encoder.SetIndent("", "  ")
	err := encoder.Encode(value)
	return output.Bytes(), err
}
func Generate(root string, check bool) error {
	c, err := catalog.Load(root)
	if err != nil {
		return err
	}
	workflow, err := Workflow(root, c)
	if err != nil {
		return err
	}

	config := Renovate(c)
	toolRules, err := ToolRules(root)
	if err != nil {
		return err
	}
	config["packageRules"] = append(config["packageRules"].([]any), toolRules...)
	renovate, err := JSON(config)
	if err != nil {
		return err
	}
	commands, err := JSON([]string{`^make (?:dev-generate|update TARGET=[a-z0-9]+(-[a-z0-9]+)+|revise-base TARGET=(?:alpine|debian|ubuntu)/[0-9]+(?:\.[0-9]+)?)$`})
	if err != nil {
		return err
	}
	for name, data := range map[string][]byte{".github/workflows/push.yml": []byte(workflow), "renovate.json": renovate, "ci/renovate-allowed-commands.json": commands} {
		path := filepath.Join(root, name)
		if check {
			existing, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			if !bytes.Equal(existing, data) {
				return fmt.Errorf("%s is stale; run make dev-generate", name)
			}
		} else if err = os.WriteFile(path, data, 0644); err != nil {
			return err
		}
	}
	return nil
}

// ToolRules derives fixed minor/base constraints from the actual pinned images.
// Changing a tool line requires editing its Dockerfile, not a second version list.
func ToolRules(root string) ([]any, error) {
	var rules []any
	pattern := regexp.MustCompile(`(?m)^(?:ARG GO_IMAGE=|FROM )([a-z]+):([0-9]+\.[0-9]+)\.[0-9]+([^@\s]*)@sha256:[a-f0-9]{64}`)
	for _, name := range []string{"Dockerfile", "Dockerfile.docs"} {
		data, err := os.ReadFile(filepath.Join(root, name))
		if err != nil {
			return nil, err
		}
		match := pattern.FindStringSubmatch(string(data))
		if match == nil {
			return nil, fmt.Errorf("%s needs a pinned tool image", name)
		}
		rules = append(rules, map[string]any{"matchDatasources": []string{"docker"}, "matchPackageNames": []string{match[1], "docker.io/library/" + match[1]}, "allowedVersions": "/^" + regexp.QuoteMeta(match[2]) + `\.[0-9]+` + regexp.QuoteMeta(match[3]) + "$/"})
	}
	return rules, nil
}
